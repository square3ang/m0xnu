#!/usr/bin/env python3
"""Turn a Mesa lima LIMA_DEBUG=dump (Mali-400, from tri.c on drm-shim) into tri_job.h.

The dump holds every buffer Mesa wrote (shaders, uniforms, RSW, command streams,
PLB/PP streams) at its GPU VA plus the GP and PP frames. Buffers Mesa did not dump
are rebuilt here: vertex data, the screen pp_buffer (frame RSW + clear program) and
GPU-written scratch (varyings, PLB, tile heap). The render target is patched at run
time to the linear framebuffer.

usage: gen_job.py lima.dump.0000 > tri_job.h
"""
import re
import struct
import sys

PAGE = 0x1000
HEAP = 0x40000  # shortcut: 256 KiB tile heap instead of Mesa's 16 MiB, enough for a few draws

# tri.c vertex arrays, at the addresses in the dump's "attribute info"
POS = [0, 0.8, -0.8, -0.8, 0.8, -0.8]
COL = [1, 0, 0, 0, 1, 0, 0, 0, 1]
# Mesa lima_screen.c pp_buffer: frame RSW at +0, PP_CLEAR_PROGRAM at +0x40
CLEAR_PROG = [0x00020425, 0x0000000c, 0x01e007cf, 0xb0000000, 0x000005f5, 0, 0, 0]


def f2u(f):
    return struct.unpack("<I", struct.pack("<f", f))[0]


def words(body):
    out = []
    for line in body.splitlines():
        line = re.sub(r"/\*.*?\*/", "", line)
        for tok in filter(None, (t.strip() for t in line.split(","))):
            out.append(int(tok, 16) if tok.startswith("0x") else f2u(float(tok)))
    return out


def parse(text):
    blobs, frames = {}, {}
    for m in re.finditer(r"^(\S[^\n]*?)(?: at va ([0-9a-f]+))?\n\{\n(.*?)^\}", text, re.M | re.S):
        name, va, body = m.group(1), m.group(2), m.group(3)
        if va:
            blobs[int(va, 16)] = (name, words(body))
        elif name.startswith("add "):
            frames[name[4:]] = words(body)
    return blobs, frames


def main():
    blobs, frames = parse(open(sys.argv[1]).read())
    gp, pp = frames["gp frame"], frames["pp frame"]
    assert len(gp) == 6 and len(pp) == 23 + 1 + 36 + 4 + 4, (len(gp), len(pp))

    attr = next(w for n, w in blobs.values() if n == "update attribute info")
    vary = next(w for n, w in blobs.values() if n == "update varying info")
    plb_stream = next(w for n, w in blobs.values() if n == "gp plb stream")
    blobs[attr[0]] = ("vertex position", [f2u(f) for f in POS])
    blobs[attr[2]] = ("vertex colour", [f2u(f) for f in COL])
    rsw_va = pp[1]
    rsw = [0] * 16
    rsw[8], rsw[9], rsw[13] = 0x0000F008, rsw_va + 0x40, 0x100
    blobs[rsw_va] = ("pp_buffer frame rsw", rsw)
    blobs[rsw_va + 0x40] = ("pp_buffer clear program", CLEAR_PROG)

    gp[4] = gp[5] - HEAP
    scratch = [(vary[0], 0x100), (gp[4], HEAP),
               (min(plb_stream), max(plb_stream) + 0x200 - min(plb_stream))]

    pages = set()
    for va, (_, w) in blobs.items():
        pages.update(range(va // PAGE, (va + 4 * len(w) - 1) // PAGE + 1))
    for va, size in scratch:
        pages.update(range(va // PAGE, (va + size - 1) // PAGE + 1))
    ranges = []
    for p in sorted(pages):
        if ranges and ranges[-1][1] == p:
            ranges[-1][1] = p + 1
        else:
            ranges.append([p, p + 1])

    o = ["/* generated by gen_job.py from a Mesa lima dump of tri.c; do not edit */",
         "static const struct mali_job_range tri_ranges[] = {"]
    o += ["\t{ %#010x, %#x }," % (a * PAGE, (b - a) * PAGE) for a, b in ranges]
    o.append("};")
    used = []
    for i, (va, (name, w)) in enumerate(sorted(blobs.items())):
        if not any(w):
            continue  # ranges start zeroed
        o.append("static const uint32_t tri_blob%d[] = {\t/* %s */" % (i, name))
        o += ["\t" + " ".join("%#010x," % x for x in w[j:j + 6]) for j in range(0, len(w), 6)]
        o.append("};")
        used.append((va, i, len(w)))
    o.append("static const struct mali_job_blob tri_blobs[] = {")
    o += ["\t{ %#010x, %d, tri_blob%d }," % (va, n, i) for va, i, n in used]
    o.append("};")
    o += ["static const struct mali_job tri_job = {",
          "\t.ranges = tri_ranges, .nranges = %d," % len(ranges),
          "\t.blobs = tri_blobs, .nblobs = %d," % len(used),
          "\t.gp = { %s }," % ", ".join("%#010x" % x for x in gp),
          "\t.pp = { %s }," % ", ".join("%#010x" % x for x in pp[:23]),
          "\t.wb = { %s }," % ", ".join("%#x" % x for x in pp[24:60]),
          "\t.plbu_array = { %s }," % ", ".join("%#010x" % x for x in pp[60:64]),
          "\t.num_pp = %d," % pp[23],
          "};"]
    print("\n".join(o))


main()
